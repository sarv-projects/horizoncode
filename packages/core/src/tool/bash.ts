/** Fail closed at the leaf even if a future registry accidentally exposes Bash. */
export const guardUnavailable = () =>
  Effect.fail(new ToolFailure({ message: "Bash is unavailable until Guarded terminal.run support is wired" }))

const layer = Layer.effectDiscard(
  Effect.gen(function* () {
    const tools = yield* Tools.Service
    yield* tools
      .register({
        [name]: Tool.make({
          description: "Shell execution is unavailable until the Guarded terminal.run path is wired.",
          // Model-visible shell identity is the guarded `terminal.run` capability (arch §33.7).
          // This leaf has no direct process implementation. It remains unavailable until
          // the canonical terminal.run challenge and one-use lease are wired here.
          capability: { id: "terminal.run", effectClass: "effect" },
          input: Input,
          output: Output,
          structured: StructuredOutput,
          toStructuredOutput: ({ output }) => ({
            truncated: output.truncated,
            ...(output.exit === undefined ? {} : { exit: output.exit }),
            ...(output.timeout === undefined ? {} : { timeout: output.timeout }),
          }),
          toModelOutput: ({ output }) => [{ type: "text", text: output.output }],
          execute: () => guardUnavailable(),
        }),
      })
      .pipe(Effect.orDie)
  }),
)

export const node = makeLocationNode({
  name: "tool/bash",
  layer,
  deps: [ToolRegistry.node],
})
